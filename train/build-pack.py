#!/usr/bin/env python3
"""Multi-character "pack" builder: N characters → one LoRA.

Discovers a franchise's characters from the Danbooru API (optionally only
those newer than a knowledge cutoff — the ones the base model can't know),
fetches each one's dataset via fetch-dataset.py, and emits a kohya dataset
config with per-character repeats balanced so a day-one character with 40
posts isn't drowned by a poster child with 4,000. Each character keeps its
own trigger word (its tag), so one pack file summons any of them.

Usage:
  build-pack.py --discover "*_(zenless_zone_zero)" --since 2024-10-23 \
      --name zzz-2025 [--min-posts 150] [--max-chars 24] [--limit 100]
  build-pack.py --chars "a_(game)" "b_(game)" --name mypack

Then: DATASET_CONFIG=train/pack-<name>.toml train/train-lora-cloud.sh <name>
"""

import argparse
import json
import pathlib
import subprocess
import sys
import urllib.parse
import urllib.request

BASE = "https://danbooru.donmai.us"
UA = {"User-Agent": "pulsar/1.0 (lora pack prep)"}
HERE = pathlib.Path(__file__).parent


def get(path: str, params: dict) -> list:
    url = f"{BASE}{path}?{urllib.parse.urlencode(params)}"
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def discover(pattern: str, since: str, min_posts: int, max_chars: int) -> list[str]:
    """Character tags matching pattern, created after `since`, by post count."""
    tags = get("/tags.json", {
        "search[name_matches]": pattern,
        "search[category]": 4,  # character
        "search[order]": "count",
        "limit": 200,
    })
    picked = []
    for t in tags:
        if t["post_count"] < min_posts:
            continue
        if since and t["created_at"][:10] <= since:
            continue
        if t["name"].endswith("_(cosplay)"):
            continue
        picked.append(t["name"])
        if len(picked) >= max_chars:
            break
    return picked


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--discover", metavar="PATTERN",
                    help="tag pattern, e.g. '*_(zenless_zone_zero)'")
    ap.add_argument("--since", default="",
                    help="only characters created after this date (the base's cutoff)")
    ap.add_argument("--chars", nargs="*", default=[],
                    help="explicit character tags instead of discovery")
    ap.add_argument("--name", required=True)
    ap.add_argument("--min-posts", type=int, default=150)
    ap.add_argument("--max-chars", type=int, default=24)
    ap.add_argument("--limit", type=int, default=100, help="images per character")
    args = ap.parse_args()

    chars = list(args.chars)
    if args.discover:
        chars += discover(args.discover, args.since, args.min_posts, args.max_chars)
    if not chars:
        print("no characters (discovery empty and none given)", file=sys.stderr)
        return 1
    print(f"pack {args.name}: {len(chars)} characters\n  " + "\n  ".join(chars))

    counts = {}
    for c in chars:
        r = subprocess.run(
            [sys.executable, str(HERE / "fetch-dataset.py"), c, "--limit", str(args.limit)],
            capture_output=True, text=True)
        sys.stdout.write(r.stdout)
        sys.stderr.write(r.stderr)
        n = len([p for p in (HERE / "dataset" / c).glob("*")
                 if p.suffix in (".jpg", ".jpeg", ".png", ".webp")])
        if n:
            counts[c] = n

    if not counts:
        print("no datasets fetched", file=sys.stderr)
        return 1

    # balance: aim every character at the largest roster's effective size,
    # capped so tiny sets don't overfit on sheer repetition
    target = max(counts.values())
    subsets = []
    for c, n in counts.items():
        repeats = min(8, max(1, round(target / n)))
        subsets.append(
            f'  [[datasets.subsets]]\n'
            f'  image_dir = "dataset/{c}"\n'
            f'  num_repeats = {repeats}\n')

    out = HERE / f"pack-{args.name}.toml"
    out.write_text(
        "# generated by build-pack.py — one LoRA, per-character trigger words\n"
        "[general]\n"
        "enable_bucket = true\n"
        'caption_extension = ".txt"\n'
        "shuffle_caption = false\n\n"
        "[[datasets]]\n"
        "resolution = 1024\n"
        "min_bucket_reso = 640\n"
        "max_bucket_reso = 1536\n"
        "batch_size = 1\n\n"
        + "\n".join(subsets))
    total = sum(counts.values())
    print(f"\n{out.name}: {len(counts)} characters, {total} images")
    print(f"train: DATASET_CONFIG=train/{out.name} train/train-lora-cloud.sh {args.name}")
    print("packs want more capacity+steps than a single character: "
          "NETWORK_DIM=32 and ~800 steps per 6 characters is a sane start")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
