// textChunks returns the iTXt chunks of a served PNG by keyword, failing on
// any chunk that is neither allow-listed nor an uncompressed iTXt, on a
// duplicate keyword, and on a text chunk placed after the pixel data.
func textChunks(t *testing.T, what string, data []byte) map[string]string {
	t.Helper()
	chunks, err := pngmeta.Chunks(data)
	if err != nil {
		t.Fatalf("%s: not a png: %v", what, err)
	}
	out := map[string]string{}
	seenIDAT := false
	for _, c := range chunks {
		if c.Type == "IDAT" {
			seenIDAT = true
		}
		if pngmeta.Allowed(c.Type) {
			continue
		}
		key, text, ok := pngmeta.ITXtText(c)
		if !ok {
			t.Fatalf("%s: carries a %s chunk that is not an uncompressed iTXt", what, c.Type)
		}
		if _, dup := out[key]; dup {
			t.Errorf("%s: duplicate %q chunk", what, key)
		}
		if seenIDAT {
			t.Errorf("%s: %q chunk sits after the pixel data", what, key)
		}
		out[key] = text
	}
	return out
}

func keysOf(m map[string]string) string {
	var ks []string
	for _, k := range []string{outmeta.KeyXMP, outmeta.KeyParameters, outmeta.KeyPulsar} {
		if _, ok := m[k]; ok {
			ks = append(ks, k)
		}
	}
	if len(ks) != len(m) {
		return "unexpected keys"
	}
	return strings.Join(ks, ",")
}

// denyList is everything the written metadata must never contain, for one
// deployment config and one job: the safety negative and the hard floor
// (from config and tags.WatchFloor(), never spelled out), DEFAULT_UC and
// QUALITY_TAGS text, the style's text, ids, paths — and the job id.
func denyList(e *env, styleText []string, ids ...string) []string {
	var deny []string
	terms := func(csv string) {
		for _, t := range strings.Split(csv, ",") {
			if t = strings.TrimSpace(t); t != "" {
				deny = append(deny, t, strings.ReplaceAll(t, "_", " "))
			}
		}
	}
	for _, t := range safetyTerms(e) {
		terms(t)
	}
	terms(e.srv.Cfg.DefaultUC)
	terms(e.srv.Cfg.QualityTags)
	for _, s := range styleText {
		terms(s)
	}
	deny = append(deny, ids...)
	return append(deny, ".safetensors", ".ckpt", ".png", "/images/", "/jobs/", "image_id", "reference_id", "mask_id",
		"class_type", "ckpt_name", "LoadImage", "Software", "NovelAI", "signed_hash")
}

func assertNoDenied(t *testing.T, what, text string, deny []string) {
	t.Helper()
	lower := strings.ToLower(text)
	for i, d := range deny {
		if strings.Contains(lower, strings.ToLower(d)) {
			t.Errorf("%s: carries deny-listed value #%d", what, i)
		}
	}
	if uuidShaped.MatchString(lower) {
		t.Errorf("%s: carries an id-shaped string", what)
	}
}

// TestServedImagesCarryOnlyTheMark: the plain URL — thumbnails, <img> — adds
// the XMP packet and nothing else; the pixels are the stored ones.
func TestServedImagesCarryOnlyTheMark(t *testing.T) {
	e := newEnv(t, "e2e_outmeta_mark", compliance.Stub{})
	id := e.generate(t, `{"prompt": "1girl, red dress", "negative": "blurry", "seed": 5}`)
	if v := e.waitTerminal(t, id); v.State != "done" {
		t.Fatalf("state = %s (%s)", v.State, v.Error)
	}
	for _, q := range []string{"", "?meta=0", "?meta=true", "?meta", "?META=1", "?other=1"} {
		status, served := fetch(t, e.ts.URL+"/images/"+id+q)
		if status != http.StatusOK {
			t.Fatalf("GET %q = %d", q, status)
		}
		tc := textChunks(t, "served"+q, served)
		if keysOf(tc) != outmeta.KeyXMP {
			t.Fatalf("%q: text chunks = %v, want the XMP mark only", q, tc)
		}
		if tc[outmeta.KeyXMP] != outmeta.XMP("txt2img") {
			t.Errorf("%q: mark = %s", q, tc[outmeta.KeyXMP])
		}
		if !strings.Contains(tc[outmeta.KeyXMP], "digitalsourcetype/trainedAlgorithmicMedia") || !strings.Contains(tc[outmeta.KeyXMP], `xmp:CreatorTool="pulsar"`) {
			t.Errorf("%q: mark does not say AI-generated by pulsar", q)
		}
		for _, leak := range []string{"1girl", "red dress", "blurry", id} {
			if bytes.Contains(served, []byte(leak)) {
				t.Errorf("%q: the plain URL carries prompt or id text", q)
			}
		}
		if !bytes.Equal(withoutMark(t, "served"+q, served, "txt2img"), e.fake.PNG) {
			t.Errorf("%q: pixels changed", q)
		}
	}
	// at rest nothing is marked: the mark is a serve-time decision
	stored, err := os.ReadFile(filepath.Join(e.blobs.Root, id+".png"))
	if err != nil {
		t.Fatal(err)
	}
	if len(textChunks(t, "stored", stored)) != 0 {
		t.Error("stored blob carries text chunks")
	}
}

// TestDownloadCarriesUserMetadataOnly: `?meta=1` adds `parameters` and
// `pulsar`, built from the job's params — and none of the deny-list, on a
// job whose stored Spec holds every deny-listed thing at once.
func TestDownloadCarriesUserMetadataOnly(t *testing.T) {
	e := newEnv(t, "e2e_outmeta_download", compliance.Stub{})
	e.srv.Cfg.DefaultUC = "lowres, bad anatomy, jpeg artifacts"
	e.fake.EmbedGraph = true

	upload := e.uploadPNG(t, 100, 150)
	// noobai + the seeded `hsr` style: prefix, suffix, negative and a LoRA file
	id := e.generate(t, `{"prompt": "acheron (honkai: star rail), 1girl, 1.3::red dress ::, -1::hat ::, !macro:Light!", "negative": "blurry",`+
		` "seed": 987654321, "lineage": "noobai", "style": "hsr", "kind": "img2img", "image_id": "`+upload+`", "steps": 22,`+
		` "chunks": [{"name": "Light", "content": "rim light"}]}`)
	v := e.waitTerminal(t, id)
	if v.State != "done" {
		t.Fatalf("state = %s (%s)", v.State, v.Error)
	}

	// the precondition: the stored params and the raw comfy output hold what must not leave
	params := string(v.Params)
	for _, must := range []string{e.srv.Cfg.ForbiddenTagUC[:4], "lowres", "masterpiece", "official art", "painterly", ".safetensors"} {
		if !strings.Contains(params, must) {
			t.Fatalf("fixture params do not carry a deny-listed value: %s", params)
		}
	}
	if !bytes.Contains(e.fake.LastGraph(), []byte(upload)) {
		t.Fatal("fixture graph does not reference the upload id")
	}
	deny := denyList(e, []string{"official art, game cg", "painterly", "logo"}, id, upload, "test-ckpt.safetensors")

	status, served := fetch(t, e.ts.URL+"/images/"+id+"?meta=1")
	if status != http.StatusOK {
		t.Fatalf("GET ?meta=1 = %d", status)
	}
	tc := textChunks(t, "download", served)
	if got := keysOf(tc); got != outmeta.KeyXMP+","+outmeta.KeyParameters+","+outmeta.KeyPulsar {
		t.Fatalf("text chunks = %s", got)
	}
	// img2img onto the user's image is a composite
	if tc[outmeta.KeyXMP] != outmeta.XMP("img2img") || !strings.Contains(tc[outmeta.KeyXMP], "compositeWithTrainedAlgorithmicMedia") {
		t.Errorf("mark = %s", tc[outmeta.KeyXMP])
	}
	for key, text := range tc {
		assertNoDenied(t, key, text, deny)
	}
	// and nowhere else in the file either (the id check covers the whole body)
	for _, raw := range []string{id, upload, e.srv.Cfg.ForbiddenTagUC} {
		if bytes.Contains(served, []byte(raw)) {
			t.Error("download carries an id or the safety negative")
		}
	}
	// the pixels are still the stored ones
	if !bytes.Equal(withoutDownloadMeta(t, served), e.fake.PNG) {
		t.Error("download changed more than the metadata")
	}

	var meta struct {
		V          int      `json:"v"`
		Prompt     string   `json:"prompt"`
		Negative   string   `json:"negative"`
		Characters []string `json:"characters"`
		Width      int      `json:"width"`
		Height     int      `json:"height"`
		Steps      int      `json:"steps"`
		CFG        float64  `json:"cfg"`
		Sampler    string   `json:"sampler"`
		Scheduler  string   `json:"scheduler"`
		Rescale    float64  `json:"rescale"`
		Seed       int64    `json:"seed"`
		Lineage    string   `json:"lineage"`
		Style      string   `json:"style"`
		Kind       string   `json:"kind"`
		Model      string   `json:"model"`
		Loras      []struct {
			Name     string  `json:"name"`
			Strength float64 `json:"strength"`
		} `json:"loras"`
		Chunks []string `json:"chunks"`
		NAI    struct {
			Prompt   string `json:"prompt"`
			Negative string `json:"negative"`
		} `json:"nai"`
	}
	var probe map[string]json.RawMessage
	if err := json.Unmarshal([]byte(tc[outmeta.KeyPulsar]), &probe); err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal([]byte(tc[outmeta.KeyPulsar]), &meta); err != nil {
		t.Fatal(err)
	}
	if meta.V != 1 || meta.Kind != "img2img" || meta.Lineage != "noobai" || meta.Style != "hsr" || meta.Seed != 987654321 ||
		meta.Steps != 22 || meta.Width != 832 || meta.Height != 1216 || meta.Sampler != "euler" || meta.CFG != 5 || meta.Rescale != 0.45 {
		t.Errorf("settings = %+v", meta)
	}
	// only the user's tags, in order; the relocated negative-weight tag lands in the negative
	if meta.Prompt != `acheron \(honkai: star rail\), 1girl, (red dress:1.2285), rim light` || meta.Negative != "blurry, hat" {
		t.Errorf("prompt = %q, negative = %q", meta.Prompt, meta.Negative)
	}
	if meta.NAI.Prompt != "acheron (honkai: star rail), 1girl, 1.3::red dress ::, rim light" || meta.NAI.Negative != "blurry, hat" {
		t.Errorf("nai = %+v", meta.NAI)
	}
	if meta.Characters == nil || len(meta.Characters) != 0 {
		t.Errorf("characters = %v, want []", meta.Characters)
	}
	// models and LoRAs as display names
	if meta.Model != "test-ckpt" || len(meta.Loras) != 1 || meta.Loras[0].Name != "honkai star rail_v3" {
		t.Errorf("model = %q, loras = %+v", meta.Model, meta.Loras)
	}
	if len(meta.Chunks) != 1 || meta.Chunks[0] != "Light" {
		t.Errorf("chunks = %v", meta.Chunks)
	}
	for _, k := range []string{"id", "job", "job_id", "image", "image_id", "upload", "reference_id", "checkpoint", "workflow", "prompt_tags", "negative_tags"} {
		if _, ok := probe[k]; ok {
			t.Errorf("pulsar chunk has a %q key", k)
		}
	}

	a := tc[outmeta.KeyParameters]
	lines := strings.Split(a, "\n")
	if len(lines) != 3 || lines[0] != meta.Prompt || lines[1] != "Negative prompt: blurry, hat" ||
		!strings.HasPrefix(lines[2], "Steps: 22, Sampler: Euler, Schedule type: Normal, CFG scale: 5, Seed: 987654321, Size: 832x1216, Model: test-ckpt, Denoising strength: 0.6, ") ||
		!strings.HasSuffix(lines[2], "Version: pulsar") {
		t.Errorf("parameters =\n%s", a)
	}
}

// withoutDownloadMeta strips a download back to its allow-listed chunks.
func withoutDownloadMeta(t *testing.T, served []byte) []byte {
	t.Helper()
	out, err := pngmeta.Strip(served)
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// Every role of a pose job is marked, and downloads with the job's metadata.
func TestPoseRolesAreMarkedAndDownloadable(t *testing.T) {
	e := newEnv(t, "e2e_outmeta_pose", compliance.Stub{})
	e.fake.TagOutputs = true
	id := e.generate(t, `{"prompt": "1girl, standing", "seed": 7, "kind": "pose"}`)
	v := e.waitTerminal(t, id)
	if v.State != "done" || len(v.Images) != 3 {
		t.Fatalf("state = %s, images = %v", v.State, v.Images)
	}
	deny := denyList(e, nil, id)
	for role, url := range v.Images {
		_, plain := fetch(t, e.ts.URL+url)
		if tc := textChunks(t, role, plain); keysOf(tc) != outmeta.KeyXMP || tc[outmeta.KeyXMP] != outmeta.XMP("pose") {
			t.Errorf("%s: plain serve text chunks = %v", role, tc)
		}
		status, dl := fetch(t, e.ts.URL+url+"?meta=1")
		if status != http.StatusOK {
			t.Fatalf("%s ?meta=1 = %d", role, status)
		}
		tc := textChunks(t, role+" download", dl)
		if keysOf(tc) != outmeta.KeyXMP+","+outmeta.KeyParameters+","+outmeta.KeyPulsar {
			t.Fatalf("%s: download text chunks = %v", role, tc)
		}
		if !strings.Contains(tc[outmeta.KeyPulsar], `"prompt":"1girl, standing"`) || !strings.Contains(tc[outmeta.KeyPulsar], `"kind":"pose"`) {
			t.Errorf("%s: pulsar chunk = %s", role, tc[outmeta.KeyPulsar])
		}
		for key, text := range tc {
			assertNoDenied(t, role+"/"+key, text, deny)
		}
		if bytes.Contains(dl, []byte(id)) {
			t.Errorf("%s: download carries the job id", role)
		}
	}
}

// A blocked job has no image on either URL: metadata opens no path around the gate.
func TestBlockedJobServesNoImageWithMeta(t *testing.T) {
	e := newEnv(t, "e2e_outmeta_blocked", denyOutput{})
	id := e.generate(t, `{"prompt": "1girl"}`)
	if v := e.waitTerminal(t, id); v.State != "blocked" || v.ImageURL != "" {
		t.Fatalf("state = %s, image_url = %q; want blocked with no image", v.State, v.ImageURL)
	}
	for _, q := range []string{"", "?meta=1"} {
		status, body := fetch(t, e.ts.URL+"/images/"+id+q)
		if status != http.StatusNotFound {
			t.Errorf("blocked image fetch %q = %d, want 404", q, status)
		}
		if bytes.Contains(body, []byte("1girl")) || bytes.Contains(body, []byte("xmp")) {
			t.Errorf("blocked image fetch %q leaked content", q)
		}
	}
}

// A blob that is not a job output (an upload) never gets prompt metadata,
// whatever the query says — there is no job row to read it from.
func TestUploadBlobGetsNoPromptMetadata(t *testing.T) {
	e := newEnv(t, "e2e_outmeta_upload", compliance.Stub{})
	upload := e.uploadPNG(t, 100, 150)
	// a job that used the upload exists; its metadata must not attach to the upload
	id := e.generate(t, `{"prompt": "1girl, red dress", "seed": 5, "kind": "img2img", "image_id": "`+upload+`"}`)
	if v := e.waitTerminal(t, id); v.State != "done" {
		t.Fatalf("state = %s (%s)", v.State, v.Error)
	}
	status, served := fetch(t, e.ts.URL+"/images/"+upload+"?meta=1")
	if status != http.StatusOK {
		t.Fatalf("GET upload = %d", status)
	}
	if tc := textChunks(t, "upload", served); keysOf(tc) != outmeta.KeyXMP {
		t.Errorf("upload text chunks = %v, want the mark only", tc)
	}
	if bytes.Contains(served, []byte("red dress")) || bytes.Contains(served, []byte(upload)) || bytes.Contains(served, []byte(id)) {
		t.Error("upload blob carries prompt or id text")
	}
}

// orbitFixture is a real `?meta=1` download, committed where orbit's reader
// tests load it (orbit/tests/imgmeta-pulsar-roundtrip.test.ts). The writer
// here and the reader there are pinned to the same bytes: this test fails
// when core's output drifts from the fixture, and orbit's fails when the
// reader no longer understands it. Regenerate with
// PULSAR_UPDATE_FIXTURES=1 go test ./internal/api -run TestDownloadFixtureMatchesOrbit
const orbitFixture = "../../../orbit/tests/fixtures/pulsar-download.png"

func TestDownloadFixtureMatchesOrbit(t *testing.T) {
	e := newEnv(t, "e2e_outmeta_fixture", compliance.Stub{})
	e.srv.Cfg.DefaultUC = "lowres, bad anatomy"
	id := e.generate(t, `{"prompt": "2girls, garden, 1.3::red dress ::, <not html>, -1::hat ::, !macro:Light!", "negative": "blurry, 1.2::extra fingers ::",`+
		` "seed": 4242424242, "lineage": "noobai", "style": "chibi", "hires": true, "steps": 22, "width": 1216, "height": 832,`+
		` "characters": [{"prompt": "silver hair, 1.2::smile ::"}, {"prompt": "black hair, school uniform"}],`+
		` "chunks": [{"name": "Light", "content": "rim light, golden hour"}]}`)
	if v := e.waitTerminal(t, id); v.State != "done" {
		t.Fatalf("state = %s (%s)", v.State, v.Error)
	}
	status, served := fetch(t, e.ts.URL+"/images/"+id+"?meta=1")
	if status != http.StatusOK {
		t.Fatalf("GET ?meta=1 = %d", status)
	}
	live := textChunks(t, "download", served)
	if os.Getenv("PULSAR_UPDATE_FIXTURES") == "1" {
		if err := os.WriteFile(orbitFixture, served, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	fixture, err := os.ReadFile(orbitFixture)
	if err != nil {
		t.Fatalf("orbit fixture missing (regenerate with PULSAR_UPDATE_FIXTURES=1): %v", err)
	}
	want := textChunks(t, "fixture", fixture)
	if len(want) != 3 || len(live) != 3 {
		t.Fatalf("fixture has %d text chunks, live has %d; want 3", len(want), len(live))
	}
	for key, text := range live {
		if want[key] != text {
			t.Errorf("%q drifted from the orbit fixture (regenerate with PULSAR_UPDATE_FIXTURES=1 and re-run orbit's tests)\n live %s\n file %s", key, text, want[key])
		}
	}
	// (the chibi style's only tag equals its slug, which is written by design,
	// so style text is checked in TestDownloadCarriesUserMetadataOnly instead)
	assertNoDenied(t, "fixture", string(fixture), denyList(e, nil, id))
}
